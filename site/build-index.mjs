// Builds site/search-index.js: the plain text of every note, so the site can search inside notes
// even when opened straight from disk (where it isn't allowed to read other files).
// Notes git ignores go to site/search-local.js instead, gitignored too, with their ids, so the menu marks only
// the others with a Git watermark.
// Run after adding or changing a note:  node site/build-index.mjs
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const entities = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", nbsp: " " };

const toText = html => html
  .replace(/<head[\s\S]*?<\/head>|<script[\s\S]*?<\/script>|<style[\s\S]*?<\/style>|<!--[\s\S]*?-->/gi, " ")
  .replace(/<[^>]+>/g, " ")
  .replace(/&(#x?[0-9a-f]+|\w+);/gi, (m, e) =>
    e[0] === "#" ? String.fromCodePoint(e[1].toLowerCase() === "x" ? parseInt(e.slice(2), 16) : +e.slice(1))
                 : entities[e.toLowerCase()] ?? m)
  .replace(/\s+/g, " ")
  .trim();

// The catalogue, for the header of chalk-markup notes and the names of [[note-id]] links
const window = {};
for (const f of ["notes.js", "notes-local.js"])     // notes-local.js: the private entries, when present
  if (existsSync(join(root, "site", f))) new Function("window", readFileSync(join(root, "site", f), "utf8"))(window);
const nn = n => String(n.n).padStart(2, "0");
const noteName = id => { const n = window.CHALK_NOTES.find(x => x.id === id); return n ? `${nn(n)} ${n.title}` : id; };

// A chalk-markup note keeps its text in <script type=text/chalk> (see notes/note.js): index that, markup symbols out
const decode = s => s.replace(/&(#x?[0-9a-f]+|\w+);/gi, (m, e) =>
  e[0] === "#" ? String.fromCodePoint(e[1].toLowerCase() === "x" ? parseInt(e.slice(2), 16) : +e.slice(1)) : entities[e.toLowerCase()] ?? m);
const stripTags = s => decode(s.replace(/<[^>]+>/g, " "));
const chalkText = (src, id) => {
  const n = window.CHALK_NOTES.find(x => x.id === id), p = n && window.CHALK_PROJECTS[n.project];
  const lines = src.replace(/^\s*\n/, "").split("\n");
  // Header from the catalogue, unless the note replaces its eyebrow or title with a raw line
  let eyebrow = n ? [p?.name, nn(n), n.module ? `Module ${n.module}` : n.context, n.date].filter(Boolean).join(" · ") : "", title = n?.title ?? "";
  while (/^<(span class="eyebrow"|h1)/.test(lines[0] || "")) {
    const l = lines.shift();
    if (l.startsWith("<span")) eyebrow = stripTags(l); else if (l.startsWith("<h1")) title = stripTags(l);
  }
  let fence = "";    // "code" or "html" inside a ``` block
  const body = lines.map(l => {
    if (/^```/.test(l)) {
      if (fence) { fence = ""; return ""; }
      fence = /^```html$/.test(l) ? "html" : "code";
      return fence === "code" ? l.replace(/^```[^:]*(?:: (.*))?$/, "$1") : "";
    }
    if (fence === "html") return stripTags(l);
    if (fence) return l.replace(/\s{2,}»\s*/, " ");
    if (l === "{keep}" || l === "---") return "";
    return l
      .replace(/^#+ |^- |^\d+\. |^>(\{\w+\})? /, "")
      .replace(/ \{\w+\}$/, "")
      .replace(/^(cause|fix): /, (m, k) => `${k.toUpperCase()} `)
      .replace(/\[\[([a-z0-9-]+)\|([^\]]+)\]\]|\[\[([a-z0-9-]+)\]\]/g, (m, a, t, b) => t ?? noteName(b))
      .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
      .replace(/`[^`]*`|<\/?(?:span|br|s|kbd|sup|sub)\b[^>]*>/g, m => m[0] === "`" ? m : "")    // tags, but not in `code`
      .replace(/\*\*|`|\\(?=\|)/g, "").replace(/(^|\s)\|(?=\s|$)/g, " ").replace(/^\||\|$/g, "")
      .replace(/(^|[^\w*])\*([^*\s][^*]*?)\*(?![\w*])/g, "$1$2");
  });
  return `${eyebrow} ${title} ${body.join(" ")}`.replace(/\s+/g, " ").trim();
};

const text = {};
for (const file of readdirSync(join(root, "notes")).filter(f => f.endsWith(".html")).sort()) {
  const html = readFileSync(join(root, "notes", file), "utf8"), id = file.slice(0, -5);
  const chalk = html.match(/<script type=["']?text\/chalk["']?>([\s\S]*?)<\/script>/);
  text[id] = chalk ? chalkText(chalk[1], id) : toText(html);
}

// Notes matched by .gitignore, tracked or not (--no-index); exit 1 means none, anything else means no git
const ignored = spawnSync("git", ["check-ignore", "--no-index", "--stdin"],
  { cwd: root, encoding: "utf8", input: Object.keys(text).map(id => `notes/${id}.html`).join("\n") });
const local = ignored.status === 0 ? ignored.stdout.split("\n").filter(Boolean).map(f => f.slice(6, -5)) : [];

const pick = keep => Object.fromEntries(Object.entries(text).filter(([id]) => local.includes(id) === keep));

writeFileSync(join(root, "site", "search-index.js"),
  "/* Generated by site/build-index.mjs — do not edit by hand. The plain text of every committed note, for search. */\n" +
  `window.CHALK_TEXT = ${JSON.stringify(pick(false), null, 1)};\n`);
writeFileSync(join(root, "site", "search-local.js"),
  "/* Generated by site/build-index.mjs — do not edit by hand. Gitignored: the notes git ignores, and their text. */\n" +
  `window.CHALK_LOCAL = ${JSON.stringify(local)};\n` +
  `Object.assign(window.CHALK_TEXT ??= {}, ${JSON.stringify(pick(true), null, 1)});\n`);
console.log(`search index: ${Object.keys(text).length - local.length} notes, ${local.length} local`);
